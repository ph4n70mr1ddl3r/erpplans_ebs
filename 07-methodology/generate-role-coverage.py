        header = "| Role | Dept / source | " + ("HC | " if b == "hq" else "") + \
                 "Owns | Participant | Step-R | Step-A | Touched | T1 | T2 | T3 |"
        a(header)
        a("|---|---|" + ("---|" if b == "hq" else "") + "---|---|---|---|---|---|---|---|")
        for r in subset:
            hc = str(r["hc"]) if b == "hq" and r["hc"] else "—"
            dept = re.sub(r"\s*\(\d+.*\)$", "", r["dept"]) if b in ("hq", "dept") else r["dept"]
