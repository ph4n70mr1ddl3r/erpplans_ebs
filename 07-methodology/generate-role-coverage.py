def split_owner_parts(raw):
    """Slash-split an Owner cell for the part-fallback, re-merging parts whose
    parentheses were split across a slash boundary ('Procurement (VS-03 /
    VS-34)' naive-splits into 'Procurement (VS-03' + 'VS-34)'; the re-merge
    reconstructs the balanced form so the parenthetical is stripped normally
    by key()). Thirty-second-wave fix.
    """
    parts = [p.strip() for p in re.split(r"\s*[;/]\s*", raw) if p.strip()]
    merged = []
    for p in parts:
        if merged and merged[-1].count("(") != merged[-1].count(")"):
            merged[-1] = merged[-1] + " / " + p
        else:
            merged.append(p)
    return merged


def split_owner_parts_w36(raw):
    """Wave-36 extension: additionally splits '+'-joined and dash-joined
    compound cells ('VP Merchandising + CFO', 'Finance \u2013 Tax'). Tried
    ONLY after the classic ';/'-split fails, so every wave-32 resolution
    (some of them whole-compound alias keys carrying dashes) is preserved.
    """
    parts = [p.strip() for p in re.split(r"\s*[;/+]\s*|\s+[\u2013\u2014-]\s+", raw) if p.strip()]
    merged = []
    for p in parts:
        if merged and merged[-1].count("(") != merged[-1].count(")"):
            merged[-1] = merged[-1] + " / " + p
        else:
            merged.append(p)
    return merged


def census():
    """Owner-resolution census over the unique workflow catalog.

    Re-derives, every run, the numbers the role-vocabulary governance baseline
    is pinned against: how many workflows' Owner cells resolve through the
    resolution order (whole-string first, then the slash-part fallback — the
    same semantics as build()'s touch()), and the size of the uncharted
    watchlist. validate-repo.sh Check 71 pins these numbers, so any corpus,
    alias, register or resolver change that moves them forces a conscious
    re-adjudication with the baseline re-pointed (the Check-74 deferred-anchor
    pattern; armed by the 2026-09-15 thirty-first-wave review).
    """
    wfs, tier, rows, dept_order, anchor = build()
    hq, dc, store, dorder = parse_toc()
    res = Resolver(hq, dc, store, dorder)

    # governance integrity: every non-prefixed ROLE_ALIASES value must resolve
    # to a real org actor (register title / roster / external) — a typo'd value
    # would otherwise silently become a phantom IT-bucket row; every
    # DEPT_ACTORS value must be a known department label.
    for ak, av in list(ROLE_ALIASES.items()) + list(ROLE_ALIASES_W36.items()) + list(ROLE_ALIASES_W38.items()) + list(ROLE_ALIASES_W39.items()):
        if av.startswith(("STORE:", "DC:", "EXTERNAL:")):
            continue
        b, dept, _, _ = res.resolve(av)
        if b == "unc" or (b == "hq" and dept == "Information Technology (product model)"):
            print(f"CENSUS-ERROR alias {ak!r} -> {av!r}: target does not resolve to a "
                  f"register title, roster role or IT seat (phantom row)")
            return 1
    _hq_depts = {v[1] for v in hq.values()}
    _known_labels = _hq_depts | {
        "Finance & Accounting (FP&A)", "Finance & Accounting (Tax)",
        "Human Resources (Payroll)", "Merchandising & Buying (Master Data)",
        "Merchandising & Buying (Direct Sourcing)", "Marketing (Loyalty)",
        "Strategy / Corporate Planning (PMO)", "Digital Commerce (IT-built platforms)",
        "Generic / cross-department", "Data Privacy Officer (DPO)",
        "Government Affairs Manager", "Regulatory Affairs Specialist",
    }
    for dk, dv in list(DEPT_ACTORS.items()) + list(DEPT_ACTORS_W36.items()):
        b, ddept, _, _ = res.resolve(dv)
        _ok = dv in _known_labels or (b != "unc" and not (b == "hq" and ddept == "Information Technology (product model)"))
        if not _ok:
            print(f"CENSUS-ERROR dept actor {dk!r}: unknown department label or "
                  f"unresolvable target {dv!r}")
            return 1

    def owner_resolves(raw):
        b, _, _, _ = res.resolve(raw)
        if b != "unc":
            return True, [raw]
        for sp in (split_owner_parts, split_owner_parts_w36):
            parts = sp(raw)
            if len(parts) > 1:
                rs = [res.resolve(p) for p in parts]
                if all(r[0] != "unc" for r in rs):
                    return True, parts
        return False, [raw]

    resolved = uncharted = 0
    unc_owner_forms = set()
    for w in wfs:
        ok, forms = owner_resolves(w["owner"])
        if ok:
            resolved += 1
        else:
            uncharted += 1
            for f in forms:
                unc_owner_forms.add(norm(f))
    unc_rows = sum(1 for r in rows if r["bucket"] == "unc")

    # wave-38: the internal-controls-matrix Owner column — the fifth adjudicated
    # role-vocabulary surface (the register behind the 808 CTL rows). Same
    # semantics: whole-cell resolution first, then the ';/'-part fallback.
    ctl_path = os.path.join(os.path.dirname(WF), "internal-controls-matrix.md")
    ctl_rows = ctl_resolved = ctl_uncharted = 0
    ctl_unc_forms = set()
    ctl_row_re = re.compile(r"^\| (CTL-\d+) \| (.+?) \| ([PD]) \| (.+?) \| (.+?) \| (.+?) \| (.+?) \|$")
    if os.path.exists(ctl_path):
        for line in open(ctl_path, encoding="utf-8"):
            m = ctl_row_re.match(line.rstrip("\n"))
            if not m:
                continue
            ctl_rows += 1
            ok, forms = owner_resolves(m.group(5))
            if ok:
                ctl_resolved += 1
            else:
                ctl_uncharted += 1
                for f in forms:
                    ctl_unc_forms.add(norm(f))

    # wave-39: the step-Activity & analysis-field prose — the sixth adjudicated
    # role-vocabulary surface. A frozen extractor lifts candidate role spans
    # (paren-qualifier stripped, >=1 capitalized qualifier word, ending in a
    # role head noun; noise prefixes for verb/conditional openers; 'Store A/B'
    # instance labels normalized; a documented non-role span set for tool
    # names, vendor tiers, customer segments and badges), and every candidate
    # resolves through the same owner_resolves semantics as the RACI cells.
    PROSE_HEADS = (r"(?:Managers?|Directors?|Leads?|Analysts?|Specialists?|Supervisors?|"
                   r"Coordinators?|Clerks?|Officers?|Engineers?|Accountants?|Planners?|"
                   r"Buyers?|Representatives?|Reps?|Associates?|Technicians?|Assistants?|"
                   r"Attorneys?|Counsel|Chefs?|Cashiers?|Drivers?|Auditors?|Architects?|"
                   r"Admins?|Administrators?|Partners?|Controllers?|Treasurers?|"
                   r"Secretaries?|President|Chemists?|Trainers?|Recruiters?|Paralegals?|"
                   r"Underwriters?|Actuaries?|Adjusters?|Appraisers?|Surveyors?|"
                   r"Inspectors?|Installers?|Operators?|Dispatchers?|Mechanics?|"
                   r"Stewards?|Nurses?|Physicians?|Pharmacists?|Librarians?|Scientists?|"
                   r"Developers?|Designers?|Editors?|Writers?|Electricians?|Plumbers?|"
                   r"Bartenders?|Butchers?|Bakers?|Florists?|Locksmiths?|Wardens?|Marshals?)")
    PROSE_CAND = re.compile(r"\b((?:[A-Z][A-Za-z0-9&/-]*\s){1,3}" + PROSE_HEADS + r")\b")
    PROSE_NOISE = re.compile(r"^(If |Each |Affected |Your |Daily |Weekly |Monthly |Every |All |When |Where |Per |Brief |Notify |Secure |Engage |OR )")
    PROSE_NON_ROLE = {
        "Approved Mechanics", "Call Associate", "Data Quality Partners",
        "Lapsed Buyer", "Project Planner", "Project Planners",
        "Strategic Partner", "Sustainable Packaging Partner", "Visualizer Lead",
        "BuildRight Trade Partner", "Digital Payment Partner",
        "Exclusive Brand Partner", "Home Building Partner",
        "Innovation Partner", "Facebook/Meta Ads Manager",
        # 2026-09-16 fortieth-wave review: adopted Oracle product names that end
        # in a role head noun — vehicles, not people (fit-gap H11/F3).
        "Oracle Internal Controls Manager", "Oracle Property Manager",
        # 2026-09-21 batch-27: same class — the adopted TCA steward console
        # product (fit-gap D20; W253's dedup-workbench step names it).
        "Oracle Customer Data Librarian",
    }

    def _prose_candidate_resolves(span):
        if span in PROSE_NON_ROLE:
            return True
        span = re.sub(r"^Store [A-Z0-9]{1,3}\s", "Store ", span)
        span = re.sub(r"^(The|A|An)\s+", "", span)  # sentence-position articles
        return owner_resolves(span)[0]

    prose_fields = ("Pain Points", "Controls", "Automation Opportunity", "KPIs",
                    "Trigger", "Volume", "Fields", "Staffing Implication")
    prose_uncharted = 0
    prose_unc_forms = set()
    for vd in sorted(d for d in os.listdir(WF) if d.startswith("VS-")):
        dd = os.path.join(WF, vd)
        for fn in sorted(f for f in os.listdir(dd) if f.startswith("PA-") and f.endswith(".md")):
            text = open(os.path.join(dd, fn), encoding="utf-8").read()
            parts = re.split(r"^## (W\d+[A-Z]?)\. (.+)$", text, flags=re.M)
            for i in range(1, len(parts) - 2, 3):
                body = parts[i + 2]
                segs = []
                in_steps = False
                for ln in body.splitlines():
                    if re.match(r"^\|\s*#\s*\|", ln) and "Role (R)" in ln:
                        in_steps = True
                        continue
                    if in_steps:
                        if not ln.startswith("|"):
                            in_steps = False
                            continue
                        cells = [c.strip() for c in ln.strip().strip("|").split("|")]
                        if len(cells) >= 2 and not set(cells[0]) <= set("- "):
                            segs.append(cells[1])
                for field in prose_fields:
                    m = re.search(r"\| \*\*" + field + r"\*\* \|(.*?)\|", body)
                    if m:
                        segs.append(m.group(1))
                for seg in segs:
                    flat = re.sub(r"\([^)]*\)", " ", seg)
                    for m in PROSE_CAND.finditer(flat):
                        span = m.group(1).strip()
                        if PROSE_NOISE.match(span):
                            continue
                        if not _prose_candidate_resolves(span):
                            prose_uncharted += 1
                            prose_unc_forms.add(span)

    print(f"CENSUS workflows={len(wfs)} owner_resolved={resolved} "
          f"owner_uncharted={uncharted} owner_uncharted_forms={len(unc_owner_forms)} "
          f"uncharted_forms={unc_rows} "
          f"ctl_owner_cells={ctl_rows} ctl_owner_resolved={ctl_resolved} "
          f"ctl_owner_uncharted={ctl_uncharted} ctl_owner_uncharted_forms={len(ctl_unc_forms)} "
          f"prose_role_uncharted={prose_uncharted} prose_role_forms={len(prose_unc_forms)} "
          f"anchor_chartered={len(anchor['chartered'])} anchor_anchored={anchor['anchored']} "
          f"anchor_zero={len(anchor['zero'])} anchor_weak={len(anchor['weak'])}")
    return 0


def main():
    if "--census" in sys.argv:
        return census()
    wfs, tier, rows, dept_order, anchor = build()
    out = render(wfs, tier, rows, dept_order, anchor)
    if "--check" in sys.argv:
        if os.path.exists(OUT):
            shipped = open(OUT, encoding="utf-8").read()
            if shipped == out:
                print("role-coverage-matrix: byte-identical, OK")
                return 0
            import difflib
            diff = list(difflib.unified_diff(shipped.splitlines(), out.splitlines(),
                                             "shipped", "re-derived", lineterm=""))
            print(f"role-coverage-matrix DRIFT ({len(diff)} diff lines) — regenerate")
            for d in diff[:20]:
                print(d)
            return 1
        print("role-coverage-matrix missing — run without --check to generate")
        return 1
    open(OUT, "w", encoding="utf-8").write(out)
    by_bucket = defaultdict(int)
    for r in rows:
        by_bucket[r["bucket"]] += 1
    print(f"role-coverage-matrix written: {len(rows)} resolved actors over {len(wfs)} workflows "
          f"(hq {by_bucket['hq']} · it {by_bucket['it']} · store {by_bucket['store']} · dc {by_bucket['dc']} · "
          f"dept {by_bucket['dept']} · sys {by_bucket['sys']} · gov {by_bucket['gov']} · wf {by_bucket['wf']} · "
          f"ext {by_bucket['ext']} · uncharted {by_bucket['unc']})")
    unc = [r for r in rows if r["bucket"] == "unc"]
    if unc:
        print("top uncharted forms — extend ROLE_ALIASES/DEPT_ACTORS to promote them:")
        for r in sorted(unc, key=lambda r: -r["touched"])[:15]:
            print(f"  {r['touched']:4d} wf  {r['title']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
